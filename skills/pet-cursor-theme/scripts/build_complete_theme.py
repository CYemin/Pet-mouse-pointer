"""Export a configured, illustrated 17-state Windows cursor theme.

Art is generated by imagegen; this script extracts sprites and compiles formats.
Hotspot landmarks are explicit reviewed input, not inferred from the filename.
"""
from pathlib import Path
import json
import math
import shutil
import argparse
import re
import hashlib
from PIL import Image, ImageDraw, ImageFont
from build_samples import cur_file, ani_file
from cursor_launchers import write_launchers

TOOL_DIR=Path(__file__).resolve().parent
ROOT=TOOL_DIR.parent
ASSETS=ROOT/'assets/theme-expressive'
OUT=ROOT/'output/pet-handdrawn-complete'
CONFIG=ASSETS/'theme-config.json'
SIZES=(32,48,64,96,128)
ORDER=['Arrow','Help','AppStarting','Wait','Crosshair','IBeam','NWPen','No',
       'SizeNS','SizeWE','SizeNWSE','SizeNESW','SizeAll','UpArrow','Hand','Pin','Person']

def pixel_options(config,spec):
    """Pixel conversion is opt-in; state values override theme-wide defaults."""
    options={key:spec.get(key,config.get(key,default)) for key,default in
             (('pixel_art',False),('native_pixel_size',48),
              ('pixel_alpha_threshold',128),('pixel_palette_colors',None))}
    if type(options['pixel_art']) is not bool:raise ValueError('pixel_art must be a boolean')
    if options['pixel_art']:
        for key,low,high in (('native_pixel_size',1,256),('pixel_alpha_threshold',1,255),
                             ('pixel_palette_colors',2,256)):
            value=options[key]
            if key=='pixel_palette_colors' and value is None:continue
            if type(value) is not int or not low<=value<=high:
                raise ValueError(f'{key} must be an integer from {low} to {high}')
    return options

def pixel_convert(frames,options):
    """Snap alpha and optionally convert colours using one shared, undithered palette."""
    threshold=options['pixel_alpha_threshold']
    converted=[]
    for frame in frames:
        frame=frame.copy()
        frame.putalpha(frame.getchannel('A').point(lambda v:255 if v>=threshold else 0))
        converted.append(frame)
    colours=options['pixel_palette_colors']
    if colours is not None:
        pixels=[p[:3] for frame in converted for p in frame.get_flattened_data() if p[3]]
        if not pixels:raise ValueError('Pixel conversion has no opaque pixels')
        sample=Image.new('RGB',(len(pixels),1));sample.putdata(pixels)
        palette=sample.quantize(colors=colours,method=Image.Quantize.MEDIANCUT,
                                dither=Image.Dither.NONE)
        # Pillow pads palettes with black. Repeat used entries so that mapping
        # cannot introduce an extra black colour from those unused entries.
        table=palette.getpalette()
        used=[table[i*3:i*3+3] for _,i in sorted(palette.getcolors(),key=lambda item:item[1])]
        palette.putpalette([v for i in range(256) for v in used[i%len(used)]])
        for i,frame in enumerate(converted):
            colour=frame.convert('RGB').quantize(palette=palette,dither=Image.Dither.NONE).convert('RGBA')
            colour.putalpha(frame.getchannel('A'));converted[i]=colour
    # Normalize hidden RGB values so transparent pixels do not count as changes.
    for frame in converted:frame.paste((0,0,0,0),mask=frame.getchannel('A').point(lambda v:255-v))
    return converted

def animation_stats(frames,sequence,ticks):
    if not sequence or len(sequence)!=len(ticks):raise ValueError('Timing mismatch')
    if any(type(i) is not int or not 0<=i<len(frames) for i in sequence):
        raise ValueError('Sequence references an invalid frame')
    if any(type(t) is not int or t<=0 for t in ticks):raise ValueError('ANI ticks must be positive integers')
    hashes=[hashlib.sha256(f.tobytes()).digest() for f in frames]
    visible=[hashes[i] for i in sequence]
    total=sum(ticks);elapsed=0;changes=[]
    for i,duration in enumerate(ticks):
        if visible[i]!=visible[i-1]:changes.append(elapsed)
        elapsed+=duration
    gaps=[(changes[(i+1)%len(changes)]-offset)%total for i,offset in enumerate(changes)]
    return {'unique_frame_count':len(set(visible)),
            'animation_fps':round(len(sequence)*60/total,6) if len(set(visible))>1 else 0,
            'visual_fps':round(len(changes)*60/total,6),
            'peak_fps':round(60/min(gaps),6) if gaps else 0,
            'cycle_ms':round(total*1000/60,6)}

def prepare(spec,config=None):
    options=pixel_options(config or {},spec)
    image=Image.open(ROOT/spec['source']).convert('RGBA')
    cols,rows=spec.get('grid',[1,1]); w,h=image.size
    ids=spec.get('source_frames',list(range(cols*rows)))
    cells=[];points=[]
    for frame_index,i in enumerate(ids):
        rects=spec.get('source_rects')
        if rects is not None:
            if len(rects)!=len(ids):raise ValueError('One source rectangle is required per selected frame')
            rect=rects[frame_index]
            if len(rect)!=4 or any(not isinstance(v,int) for v in rect):raise ValueError('Source rectangles require integer pixels')
            x0,y0,x1,y1=rect
            if not (0<=x0<x1<=w and 0<=y0<y1<=h):raise ValueError('Source rectangle is outside the image')
        else:
            x0,y0=round(i%cols*w/cols),round(i//cols*h/rows)
            x1,y1=round((i%cols+1)*w/cols),round((i//cols+1)*h/rows)
        cell=image.crop((x0,y0,x1,y1))
        point=spec['landmarks'][frame_index]
        if spec.get('landmark_units','normalized')=='normalized':
            point=(point[0]*cell.width,point[1]*cell.height)
        points.append(tuple(round(v) for v in point));cells.append(cell)
    # A shared bounding square in hotspot-relative coordinates preserves scale
    # and prevents eye/ear movement from recentering or resizing each frame.
    boxes=[]
    for cell,(px,py) in zip(cells,points):
        bbox=cell.getchannel('A').point(lambda v:255 if
            (v>=options['pixel_alpha_threshold'] if options['pixel_art'] else v>24) else 0).getbbox()
        if not bbox:raise ValueError(f"Empty image: {spec['id']}")
        boxes.append((bbox[0]-px,bbox[1]-py,bbox[2]-px,bbox[3]-py))
    left=min(b[0] for b in boxes); top=min(b[1] for b in boxes)
    right=max(b[2] for b in boxes); bottom=max(b[3] for b in boxes)
    side=math.ceil(max(right-left,bottom-top)/.88)
    anchor=(round((side-(right-left))/2-left),round((side-(bottom-top))/2-top))
    frames=[]
    for cell,(px,py) in zip(cells,points):
        canvas=Image.new('RGBA',(side,side))
        canvas.alpha_composite(cell,(anchor[0]-px,anchor[1]-py))
        frames.append(canvas)
    if options['pixel_art']:
        native=options['native_pixel_size']
        frames=pixel_convert([f.resize((native,native),Image.Resampling.NEAREST) for f in frames],options)
        anchor=tuple(max(0,min(native-1,round(v*native/side))) for v in anchor)
        side=native
    return frames,anchor,side

def build():
    config=json.loads(CONFIG.read_text(encoding='utf-8'))
    specs={s['role']:s for s in config['states']}
    if len(config['states'])!=len(ORDER) or set(specs)!=set(ORDER):raise ValueError('Theme must cover all 17 roles exactly once')
    identifiers=[spec['id'] for spec in config['states']]
    if any(not isinstance(identifier,str) or not re.fullmatch(r'[a-z0-9][a-z0-9-]{0,63}',identifier) for identifier in identifiers):
        raise ValueError('Invalid state id')
    if len(set(identifiers))!=len(identifiers):raise ValueError('Theme state ids must be unique')
    OUT.mkdir(parents=True,exist_ok=True)
    (OUT/'frames').mkdir(exist_ok=True)
    revision=hashlib.sha256(CONFIG.read_bytes())
    for spec in config['states']:revision.update((ROOT/spec['source']).read_bytes())
    manifest={'name':config.get('name','Pet Companion — 手绘宠物指针'),'version':config.get('version','0.1.0'),
              'asset_revision':revision.hexdigest()[:12],
              'sizes':list(SIZES),'states':[],'scheme_order':ORDER,
              'system_settings_modified':False}
    manifest['pixel_art']=config.get('pixel_art',False)
    font_path=next((p for p in ('C:/Windows/Fonts/msyh.ttc','/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc','/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf') if Path(p).exists()),None)
    font=ImageFont.truetype(font_path,22) if font_path else ImageFont.load_default(size=22)
    small=ImageFont.truetype(font_path,14) if font_path else ImageFont.load_default(size=14)
    gallery=Image.new('RGB',(1200,math.ceil(17/4)*264),(244,239,230))
    gd=ImageDraw.Draw(gallery)
    for position,role in enumerate(ORDER):
        spec=specs[role]
        hotspot_overrides=spec.get('hotspot_overrides',{})
        if not isinstance(hotspot_overrides,dict):raise ValueError('hotspot_overrides must map sizes to points')
        for key,point in hotspot_overrides.items():
            if key not in {str(n) for n in SIZES}:raise ValueError('Unsupported hotspot override size')
            if not isinstance(point,(list,tuple)) or len(point)!=2 or any(type(v) is not int or not 0<=v<int(key) for v in point):
                raise ValueError('Hotspot override must be an in-bounds integer point')
        options=pixel_options(config,spec)
        raw,anchor,side=prepare(spec,config)
        resampling=Image.Resampling.NEAREST if options['pixel_art'] else Image.Resampling.LANCZOS
        animated=len(raw)>1
        sequence=spec.get('sequence',list(range(len(raw))))
        ticks=spec.get('ticks',[12]*len(sequence))
        animation_stats(raw,sequence,ticks)
        variants={}; hotspots={};stats={}
        for n in SIZES:
            folder=OUT/str(n);folder.mkdir(exist_ok=True)
            images=[f.resize((n,n),resampling) for f in raw]
            stats[str(n)]=animation_stats(images,sequence,ticks)
            hot=tuple(max(0,min(n-1,round(v*n/side))) for v in anchor)
            if str(n) in hotspot_overrides:hot=tuple(hotspot_overrides[str(n)])
            hotspots[str(n)]=hot
            cursors=[cur_file([(f,hot)]) for f in images]
            ext='ani' if animated else 'cur'
            data=ani_file(cursors,sequence,ticks) if animated else cursors[0]
            relative=f'{n}/{spec["id"]}.{ext}'
            (OUT/relative).write_bytes(data);variants[str(n)]=relative
            for k,frame in enumerate(images):frame.save(OUT/f'frames/{spec["id"]}-{n}-{k}.png')
        main=Path(variants['48']).name
        shutil.copy2(OUT/variants['48'],OUT/main)
        # A state becoming animated must not leave an obsolete CUR beside it.
        obsolete_ext='cur' if animated else 'ani'
        for folder in (OUT,*(OUT/str(n) for n in SIZES)):
            obsolete=(folder/f'{spec["id"]}.{obsolete_ext}').resolve()
            if not obsolete.is_relative_to(OUT.resolve()):raise ValueError('Output cleanup escaped theme directory')
            if obsolete.is_file():obsolete.unlink()
        display=raw[0].resize((184,184),resampling)
        x,y=position%4*300,position//4*264
        gallery.paste(display,(x+58,y+12),display)
        gd.text((x+18,y+196),f'{position+1:02d}  {spec["label"]}',font=font,fill='#43362d')
        gd.text((x+18,y+232),spec['idea'][:18],font=small,fill='#827060')
        # Each card's enlarged source preview plus a hotspot overlay for review.
        raw[0].resize((256,256),resampling).save(OUT/f'frames/{spec["id"]}-large.png')
        state={k:spec[k] for k in ('id','role','label','idea')}
        state.update(file=main,variants=variants,hotspots=hotspots,animated=animated,
                     frame_count=len(raw),sequence=sequence,ticks=ticks,
                     source=spec['source'],landmarks=spec['landmarks'])
        state.update(stats['48'])
        state.update(pixel_art=options['pixel_art'],
                     unique_frame_counts={n:v['unique_frame_count'] for n,v in stats.items()},
                     animation_stats_by_size=stats)
        if options['pixel_art']:state.update(options)
        if 'source_rects' in spec:state['source_rects']=spec['source_rects']
        if 'landmark_units' in spec:state['landmark_units']=spec['landmark_units']
        if 'motion_audit' in spec:state['motion_audit']=spec['motion_audit']
        if hotspot_overrides:state['hotspot_overrides']=hotspot_overrides
        manifest['states'].append(state)
    gallery.save(OUT/'theme-overview.png')
    (OUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    preview=(TOOL_DIR/'theme-preview.html').read_text(encoding='utf-8')
    preview=preview.replace('__MANIFEST__',json.dumps(manifest,ensure_ascii=False).replace('</','<\\/'))
    (OUT/'preview.html').write_text(preview,encoding='utf-8')
    for script in ('install-theme.ps1','restore-theme.ps1'):
        shutil.copy2(TOOL_DIR/script,OUT/script)
    write_launchers(OUT)
    print(json.dumps({'states':len(manifest['states']),'animated':sum(s['animated'] for s in manifest['states']),
                      'size_variants':len(SIZES),'output':str(OUT)},ensure_ascii=False))

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--config',type=Path)
    parser.add_argument('--output',type=Path)
    parser.add_argument('--root',type=Path,help='Base directory for source image paths')
    args=parser.parse_args()
    if args.root:ROOT=args.root.resolve()
    if args.config:CONFIG=args.config.resolve()
    if args.output:OUT=args.output.resolve()
    build()
